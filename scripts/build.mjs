// Concatenates the ordered source parts in src/ into one ES module: www/js/game.js.
// Parts share one module scope (top-level consts/functions), in file-name order.
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execSync } from 'node:child_process';
if (!existsSync('www/vendor/three/three.module.js')) execSync('node scripts/vendor.mjs', { stdio: 'inherit' });
const parts = readdirSync('src').filter(f => f.endsWith('.js')).sort();
const banner = `// Ultrablast Turbo (mobile). Generated by scripts/build.mjs from src/. Edit the files in src/, not this one.\n`;
const body = parts.map(f => `\n// ===== src/${f} =====\n` + readFileSync(`src/${f}`, 'utf8')).join('\n');
mkdirSync('www/js', { recursive: true });
writeFileSync('www/js/game.js', banner + body);
console.log(`built www/js/game.js from ${parts.length} parts`);
